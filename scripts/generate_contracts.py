"""Generate portable TypeScript schema types and OpenAPI from the same server."""
from pathlib import Path
import argparse,json,sys
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from backend.app.main import app
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();schema=app.openapi()
def ts(s):
    if '$ref'in s:return s['$ref'].split('/')[-1]
    if 'anyOf'in s:return ' | '.join(ts(x)for x in s['anyOf'])
    if 'enum'in s:return ' | '.join(json.dumps(x)for x in s['enum'])
    if 'const'in s:return json.dumps(s['const'])
    kind=s.get('type')
    if kind=='array':return '('+ts(s['items'])+')[]'
    if kind in ['integer','number']:return 'number'
    if kind=='boolean':return 'boolean'
    if kind=='string':return 'string'
    if kind=='null':return 'null'
    if kind=='object':
        props=s.get('properties',{});required=s.get('required',[])
        members=[json.dumps(k)+(''if k in required else '?')+': '+ts(v)+';'for k,v in props.items()]
        additional=s.get('additionalProperties',True)
        if additional:members.append('[key:string]: '+(ts(additional)if isinstance(additional,dict)else 'unknown')+';')
        return '{ '+ ' '.join(members)+' }'
    return 'unknown'
types='// Generated by scripts/generate_contracts.py. Source: backend OpenAPI.\n'+''.join('export type '+name+' = '+ts(value)+';\n'for name,value in schema['components']['schemas'].items())
outputs={ROOT/'docs'/'openapi.json':json.dumps(schema,indent=2),ROOT/'frontend'/'src'/'contracts.ts':types}
for path,value in outputs.items():
    if args.check:
        if not path.exists()or path.read_text(encoding='utf8')!=value:raise SystemExit('Contract drift: '+str(path))
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value,encoding='utf8')
print('OpenAPI and TypeScript contracts '+('verified'if args.check else 'generated'))
