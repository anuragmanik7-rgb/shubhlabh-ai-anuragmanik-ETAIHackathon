"""Policy compiler agreement with hand-written constraints on 40 briefs/policies.

Field agreement = expected fields compiled correctly / expected fields.
Spurious changes = fields changed that the text did not ask for.
Usage: python scripts/evaluate_compiler.py [--offline]   -> docs/evidence/compiler.json
"""
import argparse, json, sys, time
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.persistence import Store
from backend.app.seed import create_retailer
from backend.app.domain import Brief
from backend.app.compiler import compile_text, diff
from backend.app.llm import LLM

def norm(v):
    return sorted(v) if isinstance(v, list) else v

def run(use_model):
    cases = json.loads((ROOT / 'eval' / 'policies.json').read_text(encoding='utf-8'))['cases']
    store = Store('sqlite:///' + str(ROOT / 'data' / 'eval-compiler.sqlite3')); state = create_retailer()
    base = Brief().model_dump(); fields = correct = spurious = exact = 0; cost = 0.0; rows = []
    for c in cases:
        out = compile_text(store, base, c['text'], state, use_model)
        changed = {d['field'] for d in diff(base, out['brief'])}
        ok = {k: norm(out['brief'].get(k)) == norm(v) for k, v in c['expect'].items()}
        extra = sorted(changed - set(c['expect']))
        fields += len(ok); correct += sum(ok.values()); spurious += len(extra); exact += all(ok.values()) and not extra
        cost += (out.get('model_call') or {}).get('cost_usd', 0)
        rows.append({'text': c['text'], 'ok': ok, 'spurious': extra, 'method': out['method']})
    return {'field_agreement': round(correct / fields, 4), 'exact_cases': exact, 'cases': len(cases), 'spurious_changes': spurious,
            'cost_usd': round(cost, 4), 'rows': rows}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--offline', action='store_true'); args = ap.parse_args()
    res = {'offline': run(False)}
    if not args.offline:
        if not LLM.available():
            sys.exit('OPENAI_API_KEY missing; use --offline')
        res['model'] = run(True)
    out = {'cases': res['offline']['cases'],
           'field_agreement': {k: v['field_agreement'] for k, v in res.items()},
           'exact_cases': {k: v['exact_cases'] for k, v in res.items()},
           'spurious_changes': {k: v['spurious_changes'] for k, v in res.items()},
           'cost_usd': {k: v['cost_usd'] for k, v in res.items()},
           'note': 'Hand-written expected constraints; read-back is generated by code from what the solver enforces.',
           'rows': {k: v['rows'] for k, v in res.items()}, 'at': time.strftime('%Y-%m-%dT%H:%M:%S')}
    (ROOT / 'docs' / 'evidence' / 'compiler.json').write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding='utf-8')
    for k, v in res.items():
        print(k, 'agreement', v['field_agreement'], 'exact', v['exact_cases'], '/', v['cases'], 'spurious', v['spurious_changes'])
        for r in v['rows']:
            if not all(r['ok'].values()) or r['spurious']:
                print('   MISS', r['text'][:70], {a: b for a, b in r['ok'].items() if not b}, r['spurious'])

if __name__ == '__main__':
    main()
